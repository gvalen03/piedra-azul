CREATE TABLE IF NOT EXISTS aprovisionamientos_usuarios (
  id BIGSERIAL PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  rol VARCHAR(30) NOT NULL CHECK (rol IN ('PACIENTE','MEDICO_TERAPISTA','AGENDADOR','ADMINISTRADOR')),
  keycloak_subject VARCHAR(255) UNIQUE,
  estado VARCHAR(30) NOT NULL CHECK (estado IN ('PENDIENTE','KEYCLOAK_CREADO','COMPLETADO','COMPENSADO','REQUIERE_RECUPERACION')),
  solicitado_por VARCHAR(100) NOT NULL,
  detalle_error VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
